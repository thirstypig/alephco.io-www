// ── Analytics is centralised and host-guarded (session 111) ─────
//
// Every page used to inline its own GA4 snippet, calling `gtag('config', …)`
// unconditionally. That counts our own traffic: `npm run dev` serves this site on
// localhost:3060, and every local preview reported as a real visitor.
//
// The app repo had the identical defect and it was not theoretical — GA4 for
// 2026-08-03 → 2026-08-30 showed 5,109 of 5,210 "active users" coming from localhost,
// 98% noise, against 96 real marketing visitors. Fixed there in session 110; this repo
// stayed exposed for another session because nobody checked the sibling.
//
// The rule now lives once, in js/analytics.js, behind a hostname ALLOWLIST. These checks
// exist so a new page cannot quietly reintroduce an inline tag — 38 copies of a rule is
// how it drifted in the first place (DOC-062).

const analyticsJs = readFileSync(join(ROOT, "js/analytics.js"), "utf-8");

assert(
  analyticsJs.includes("ANALYTICS_HOSTS"),
  "js/analytics.js: the hostname allowlist is gone — analytics would fire everywhere"
);
assert(
  /ANALYTICS_HOSTS\s*=\s*\[[^\]]*"alephco\.io"/.test(analyticsJs),
  "js/analytics.js: alephco.io is not in the allowlist — the live site would report nothing"
);
assert(
  !/ANALYTICS_HOSTS\s*=\s*\[[^\]]*localhost/.test(analyticsJs),
  "js/analytics.js: localhost is in the allowlist — that is the bug this guard exists for"
);

// ⚠️ These two are asserted UNCONDITIONALLY, on every page.
//
// The first version of this loop skipped any page that referenced neither the Google tag
// nor js/analytics.js — reasoning that such a page has no analytics to police. A positive
// control disproved it immediately: replacing pricing.html's script tag with a bare inline
// `gtag('config', …)` removed BOTH markers, so the page was skipped and the guard stayed
// green over the exact defect it exists to catch. A gate that excuses the failure case is
// worse than no gate, because it reports success.
let analyticsRefs = 0;
for (const page of ALL_HTML_FILES) {
  const html = readFileSync(join(ROOT, page), "utf-8");
  if (html.includes('src="/js/analytics.js"')) analyticsRefs++;

  assert(
    !/gtag\(\s*['"]config['"]/.test(html),
    `${page}: inlines gtag('config', …) — move it to js/analytics.js so the host guard applies`
  );
  assert(
    !html.includes("googletagmanager"),
    `${page}: loads the Google tag directly, bypassing the hostname allowlist in js/analytics.js`
  );
}

// …and the counterpart: the guarded loader must actually still be referenced. Without this,
// deleting every script tag would satisfy both assertions above by removing analytics
// entirely, which is "green" for the wrong reason.
assert(
  analyticsRefs >= 30,
  `only ${analyticsRefs} pages reference /js/analytics.js — analytics has been dropped, not guarded`
);
assert(
  readFileSync(join(ROOT, "index.html"), "utf-8").includes('src="/js/analytics.js"'),
  "index.html does not reference /js/analytics.js — the homepage would report nothing"
);

// ── …and assert what it DOES, not just what it says ─────────────
//
// Everything above is string matching, which proves the allowlist is spelled correctly and
// nothing more. Run the actual file against a fake window for a real hostname and a local
// one, and check the observable outcome: does it append a Google tag script, and is
// `window.gtag` live or inert afterwards?
function runAnalyticsOn(hostname) {
  const appended = [];
  const fakeWindow = {
    location: { hostname },
    dataLayer: undefined,
    gtag: undefined,
  };
  const fakeDocument = {
    createElement: () => ({}),
    head: { appendChild: (el) => appended.push(el) },
  };
  new Function("window", "document", analyticsJs)(fakeWindow, fakeDocument);
  fakeWindow.gtag("event", "page_view");
  return { appended, dataLayerLength: fakeWindow.dataLayer.length };
}

const live = runAnalyticsOn("alephco.io");
assert(
  live.appended.length === 1,
  "js/analytics.js: does NOT load the Google tag on alephco.io — the live site would report nothing"
);
assert(
  live.dataLayerLength > 1,
  "js/analytics.js: gtag is inert on alephco.io — the live site would report nothing"
);

for (const host of ["localhost", "127.0.0.1", "thirstypig.github.io", "staging.alephco.io"]) {
  const off = runAnalyticsOn(host);
  assert(
    off.appended.length === 0,
    `js/analytics.js: loads the Google tag on ${host} — an unlisted host must stay silent`
  );
  // The `js` call happens before the host check, so dataLayer holds exactly that one entry.
  // A second entry means the post-guard gtag was still live and our own traffic is counted.
  assert(
    off.dataLayerLength === 1,
    `js/analytics.js: gtag still records events on ${host} — this is the 98%-noise bug`
  );
}

// ── Report ──────────────────────────────────────────────────────
console.log("");
if (failed === 0) {
  console.log(
    `\u2713 All ${passed} checks passed across ${PAGES.length} pages, ${Object.keys(REDIRECT_PAGES).length} redirect stubs and ${EXEMPT_PAGES.size} exempt files`
  );
} else {
  console.log(`\u2717 ${failed} of ${passed + failed} checks failed:\n`);
  for (const f of failures) {
    console.log(`  - ${f}`);
  }
}
console.log("");
process.exit(failed > 0 ? 1 : 0);
